export function pickWord(pool: string[], usedFirstLetters: Set<string>): string {
  // Try up to 40 random picks to avoid starting-letter collision
  for (let i = 0; i < 40; i++) {
    const candidate = pool[Math.floor(Math.random() * pool.length)];
    if (!usedFirstLetters.has(candidate[0])) {
      return candidate;
    }
  }
  // Fallback: scan for any unused starting letter
  for (let i = 0; i < pool.length; i++) {
    const candidate = pool[i];
    if (!usedFirstLetters.has(candidate[0])) {
      return candidate;
    }
  }
  // Last resort: random
  return pool[Math.floor(Math.random() * pool.length)];
}
